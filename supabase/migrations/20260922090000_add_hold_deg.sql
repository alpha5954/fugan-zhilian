-- ============================================================================
-- 迁移 9：训练记录增加「保持角度」
-- ============================================================================
--
-- 【为什么需要它】
-- 四个康复动作里，**靠墙静蹲是静力动作**：它的目标 55° 指的是
-- 「保持角度」，而表里在此之前只有 rom_deg（关节活动范围）。
--
-- 静蹲的活动范围天然只有 5~10°（只有姿势微调），拿它去比 55° 会得出
-- 接近 0 的完成度 —— 一个做得完全正确的患者会被判成 0 分。
--
-- 所以在此之前，**前端两处都只能整个跳过静力动作**：
--   * src/lib/analysis.ts 的 summarize() —— 不计入达标统计
--   * src/lib/insight.ts 的 completionOf() —— 不参与恢复评分
--
-- 后果是这类动作在评估体系里完全不存在：一个只做静蹲的患者，
-- 达标次数永远是 0，恢复评分里"动作达标"那一项也永远是 0。
--
-- 这一列补上之后，两处都能按动作类型取对应的指标。
--
-- 【为什么可空】
--   1. 动态动作没有保持角度这个概念，就该是 null
--   2. 历史记录没有这个值，补 0 会被当成"保持角度为 0"参与评分，
--      比 null 更糟 —— 代码里对 null 的处理是"跳过"，对 0 是"算 0 分"
--
-- 【为什么不做回填】
-- 历史记录里的 rom_deg 已经存了，但静力动作的**保持角度**（该次动作达到的
-- 最大屈曲角）当时只存在前端内存里，没有落库，现在无法还原。
-- 回填任何值都是编造。老记录就让它保持 null，评分时跳过 ——
-- 宁可少算，也不要算错。
-- ============================================================================

alter table public.rehab_sessions
  add column if not exists hold_deg numeric(5, 2);

comment on column public.rehab_sessions.hold_deg is
  '静力动作的保持角度（度）。动态动作为 null。'
  '达标判定用它而不是 rom_deg —— 见 src/lib/assessment.ts 的 AssessMetric。';

-- 静力动作按 (患者, 动作) 查历史时用得上；量小，部分索引即可
create index if not exists rehab_sessions_hold_idx
  on public.rehab_sessions (patient_id, exercise)
  where hold_deg is not null;
