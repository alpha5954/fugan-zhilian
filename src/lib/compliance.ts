// ============================================================================
// 合规边界：措辞的硬线
// ============================================================================
// 这个产品**不是医疗器械**，没有 NMPA 注册。所以措辞有一条硬线：
//
//   ✗ 不能给疾病名称      「膝关节僵硬症」「股四头肌萎缩」
//   ✗ 不能说「诊断为…」
//   ✗ 不能给治疗方案      药物、剂量、手术指征
//   ✓ 可以描述测量结果    「活动度 62°，低于康复目标 90°」
//   ✓ 可以描述功能状态    「本次屈曲幅度不足」
//   ✓ 可以给训练建议      「在无痛范围内逐步增加幅度」
//   ✓ 可以报安全风险      「皮温接近阈值」
//
// **一条可操作的判据：结论的主语必须是「数据」或「训练」，不能是「患者」。**
//
//   ✗  你的膝关节僵硬了            ← 对患者下判断
//   ✓  本次膝关节屈曲活动度低于目标   ← 对测量结果下判断
//
// ============================================================================
// 【为什么单独一个模块，而不是写在 findings.ts 里】
// ============================================================================
// 这条线原先只有**一个**执行点：规则层写文案时人盯着，外加
// scripts/check-findings.ts 对产物过筛。
//
// 接上 AI 之后变成**两个**执行点 —— AI 会现场生成新句子，那句话没人盯过。
// 于是需要在运行时过滤它的输出（src/lib/aiReply.ts）。
//
// 如果那时在 aiReply 里再抄一份禁词表，就是**两份会各自漂移的规则**。
// 这个仓库已经记录过两次同类事故（DemoNotice 里传感器参数在「关于」页和
// 首页折叠区各有一份；FindingCard 里"同一个结论在不同页面看起来是两个
// 等级"）。所以列表只留一处，两个执行点都 import 它。
//
// ============================================================================
// ⚠️ 这个过滤器的能力边界（不要 overclaim）
// ============================================================================
// 它是**关键词匹配 + 句首启发式**，不是语言理解。它挡得住明写的疾病名和
// 治疗方案，挡不住：
//
//   · 换一种说法绕过去（「关节活动受限」不带病名，但接近判断）
//   · **药名本身**。这张表拦的是「服用」「用药」这类**动词**，不是药名 ——
//     实测「建议服用布洛芬」是靠补上「服用」才拦下的。去掉动词只写
//     「建议布洛芬」，这里就拦不住。药名是开放集合，关键词表天生管不了，
//     真正的防线是提示词里禁止给治疗方案
//   · 完全不带这些词、但语义上仍然是在对患者下判断的句子
//   · 把「无痛」「正常」这类词用在错误的地方
//
// 所以界面上只能标注「由 AI 生成」，**绝不能写「内容已合规校验」**——
// 那是把一个尽力而为的过滤器说成了保证。
// ============================================================================

/**
 * 诊断动作 + 疾病 / 病理名称。
 *
 * ⚠️ **这一类在哪儿都不许出现，包括拒答里。**
 *    「不能判断是不是关节炎」这种句子要拦 —— 它把病名摆到家属面前了，
 *    哪怕是以否定的形式。
 *
 * 「症 / 炎」这类单字是**故意放宽匹配**的：「膝关节僵硬症」「关节炎」
 * 「肌腱炎」都靠它们拦下。代价是可能误伤正常用词 —— 实测规则层现有的
 * 全部文案（23 条）零误伤，所以这个代价目前不成立。
 */
const DISEASE_TERMS: readonly string[] = [
  // 诊断动作
  '诊断',
  '确诊',
  '疑似',
  // 疾病 / 病理名称
  '症',
  '炎',
  '病变',
  '萎缩',
  '粘连',
  '畸形',
  '骨折',
  '损伤',
  '退变',
  '坏死',
] as const

/**
 * 治疗方案的**类别词**。
 *
 * ⚠️ **这一类只在"回答"里禁，在"拒答"里放行。**
 *
 * 这个区分是 2026-09-24 打真实调用才发现的，而且当时**误杀的是一次正确
 * 行为**：模型面对提示词注入时正确地拒答了，写的是
 *
 *   「用药问题需要由医生判断，这份训练数据里没有相关内容。」
 *
 * 而禁词表把「用药」当治疗方案拦了下来 —— 于是这条拒答被丢掉，界面上
 * 表现成"AI 出错了"。
 *
 * 区别在于：「用药」是个**类别**，「关节炎」是个**具体病名**。
 *   · 在拒答里说「用药问题需要医生判断」—— 无害，它就是在拒绝给方案
 *   · 在拒答里说「不能判断是不是关节炎」—— 有害，具体病名被说出来了
 *
 * 所以拒答这一侧放宽到只禁病名。拒答本身就是安全动作，
 * **把一次正确的拒答丢掉，比放过一句含类别词的拒答糟得多**。
 */
const TREATMENT_TERMS: readonly string[] = [
  '处方',
  '服药',
  '服用',
  '口服',
  '吃药',
  '用药',
  '药物',
  '剂量',
  '手术',
  '注射',
  '针灸',
] as const

/**
 * 全部禁用词（两类合起来）。
 *
 * 评估结论文本那一侧（scripts/check-findings.ts）用的是这一份 ——
 * 那里的文案是我们自己手写的短句，不存在"拒答"这个场合，所以不区分。
 *
 * ⚠️ 改这张表要连带跑 `npm run check:findings`。
 */
export const BANNED_TERMS: readonly string[] = [
  ...DISEASE_TERMS,
  ...TREATMENT_TERMS,
] as const

/**
 * 作主语时不许出现的词。
 *
 * 「患者」本身不是禁词 —— 它作为**容器**是正常的（「患者的训练记录」）。
 * 被禁的是它**作句子主语**去接一个判断（「患者存在肌力不足」）。
 * 所以这个表只在句首生效，见 `complianceIssue`。
 */
const PATIENT_SUBJECTS: readonly string[] = ['你', '您', '患者', '病人']

/** 句首可能出现的指代修饰词，先剥掉再判断主语 */
const LEADING_DETERMINERS = /^[该此本这那些]+/

/** 切句。中英文句末标点都算，换行也算 */
const SENTENCE_SPLIT = /[。！？；!?;\n]+/

/** 句首取几个字用来判断主语。「该患者」剥掉「该」之后还剩两字，取 3 足够 */
const HEAD_LEN = 3

export interface ComplianceOptions {
  /**
   * 这段文字是**拒答**。
   *
   * 放宽治疗方案的类别词（`TREATMENT_TERMS`），但仍然禁病名。
   * 理由见 `TREATMENT_TERMS` 那段 —— 简单说：
   * **拒答本身是安全动作，把一次正确的拒答丢掉比放过一句含类别词的拒答糟。**
   */
  inDecline?: boolean
}

/**
 * 检查一段文本有没有越过合规线。
 *
 * @returns 越界时返回一句中文原因（给日志和自检看），没有越界返回 null
 *
 * 【为什么返回原因而不是布尔】
 * 调用方需要区分「因为病名被拒」和「因为数值对不上被拒」—— 排查时两者
 * 的修法完全不同。返回 `false` 的话，出了问题只能靠猜。
 */
export function complianceIssue(
  text: string,
  opts: ComplianceOptions = {},
): string | null {
  if (!text) return null

  const words = opts.inDecline
    ? DISEASE_TERMS
    : [...DISEASE_TERMS, ...TREATMENT_TERMS]

  for (const word of words) {
    if (text.includes(word)) return `出现禁用词「${word}」`
  }

  for (const sentence of text.split(SENTENCE_SPLIT)) {
    const head = sentence.trim().replace(LEADING_DETERMINERS, '').slice(0, HEAD_LEN)
    if (!head) continue

    for (const subject of PATIENT_SUBJECTS) {
      if (head.startsWith(subject)) {
        return `句子主语是「${subject}」，应当用「本周训练」「动作数据」这类`
      }
    }
  }

  return null
}
