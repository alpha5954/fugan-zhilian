/**
 * 本周有多少次会话才算"数据充足"。
 *
 * [待核定] 5 次是拟的。
 *
 * 少于这个数时，分数会按比例向中性值收敛 —— 否则"本周只练了 1 次"
 * 也能算出一个看起来很确切的分数。实测过：1 次做满得 85 分、
 * 1 次不达标得 30 分，**1 个样本给出了 55 分的区分度**，这不合理。
 */
export const SUFFICIENT_SESSIONS = 5

/**
 * 数据不足时分数向这个值收敛。
 *
 * 【为什么是 65 而不是 60】
 * 60 正好压在"黄灯 / 红灯"的分界线上。收缩之后所有分数都会向中性值
 * 聚拢，落在分界线附近时，**颜色就由噪声决定了** —— 实测出现过
 * "1 次做满 61 分显示黄灯、1 次三成 56 分显示红灯"，5 分之差跨了一个
 * 颜色档，而两者的数据量同样不足，不该有这种区分。
 *
 * 取 65 落在中间档内部，避免这个问题。值本身表达的是"还看不出来"。
 */
export const NEUTRAL_SCORE = 65

