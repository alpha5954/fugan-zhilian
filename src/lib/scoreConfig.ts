// ---------------------------------------------------------------------------
// 九、评估结论（lib/findings.ts）
// ---------------------------------------------------------------------------
// 这一组原先**直接写在 findings.ts 里**，违反了本文件开头那条规矩
// （"算法实现里不再出现裸常数"）。搬过来的同时改了一处，见
// SINGLE_PROGRESS_THRESHOLD 的注释。
//
// ⚠️ 这里有两组容易混的阈值，先分清它们**量的不是一回事**：
//
//   PROGRESS_FULL_SWING（第二节）  量的是一**周**均值 vs 前两周均值，
//                                  决定评分里"进步情况"能拿多少分。
//                                  0 对应持平，±20% 对应满分/零分。
//
//   SINGLE_PROGRESS_THRESHOLD（本节）量的是一**次**训练 vs 同动作历史均值，
//                                  决定评估页要不要说"较以往有进步"。
//
//   两个数不一样是应该的（平均之后噪声小、单次波动大），但**不能让同一个
//   数字在两处得出相反的结论** —— 单次 +6% 说"有进步"而周度 +6% 说"基本
//   持平"，用户在两页之间来回看就会发现。所以单次的阈值必须更高，而不是更低。
// ---------------------------------------------------------------------------

/**
 * 完成度低于目标的多少，算"差得严重"（红灯）而不是"需要注意"（黄灯）。
 *
 * [待核定] 0.3 是拟的，意思是"差了目标的三成"。
 * 差 3° 和差 40° 不该是同一句话。
 */
export const SHORTFALL_CRITICAL = 0.3

/**
 * 单次训练相对历史均值变化多少，才说"有进步 / 有回落"。
 *
 * ⚠️ **这个数被改过，原来是不假思索的 0.05。**
 *
 * 【为什么 0.05 是错的】
 * 它低于测量误差。本文件第二节已经算过：膝关节活动度的**最小可检测变化
 * （MDC）**大约 5°~10°，换算成相对值约 6%~11% —— 也就是说，
 * 小于 MDC 的变化**无法与测量误差区分**。
 *
 * 拿 5% 当门槛，等于把传感器的噪声和患者当天的状态起伏都报成"有进步"。
 * 康复中的家属看到"较以往有进步"会真的以为好转了。
 *
 * 【为什么取 0.12】
 * 取 MDC 相对值区间的上沿。宁可不报，也不要报一个和噪声分不开的"进步"。
 * 平台上显示的每一次"进步"都应该是可信的。
 *
 * [待核定] MDC 的区间本身来自常见做法，需要康复科确认具体数值。
 */
export const SINGLE_PROGRESS_THRESHOLD = 0.12

/**
 * 单次进步至少要有几条同动作历史才给结论。
 *
 * 用两三条记录算出来的"进步 30%"只会误导人。
 */
export const MIN_SINGLE_HISTORY = 3

/**
 * 肌电-运动学相位比低于多少算"发力时机偏晚"。
 *
 * 向心期与离心期的 RMS 之比，正常应明显大于 1（屈曲时主动发力）。
 */
export const PHASE_RATIO_MIN = 0.9

/**
 * 一次训练内各轮次的活动度变异系数超过多少算"幅度不稳"。
 *
 * ⚠️ 别和「动作稳定」那一项搞混 —— 那个量的是**次与次之间**的波动
 *    （见 STABILITY_CV_LIMIT），这个量的是**一次训练内轮与轮之间**。
 *    两件事，两套阈值，界面上的措辞也必须分开。
 *
 * [待核定] 0.15 是拟的。
 */
export const REP_ROM_CV_LIMIT = 0.15

/** 后半程肌电强度比前半程下降多少算"疲劳"。 */
export const FATIGUE_DROP = 0.25

/** 后半程肌电强度上升多少算"越做越有力"。正值，内部会取反 */
export const FATIGUE_RISE = 0.2

/** 动作识别置信度低于多少要提醒 */
export const CONFIDENCE_MIN = 0.7

/** 少于这么多次就估不出趋势（疲劳、轮次稳定性都要用） */
export const MIN_REPS_FOR_TREND = 4

/**
 * 评估结论默认一次给几条。
 *
 * 一次冒五条并列的结论，等于一条都没说 —— 用户会全部略过。
 */
export const TOP_FINDINGS = 3

// ---------------------------------------------------------------------------
// 十、进展趋势（lib/trend.ts，数据分析页的结论）
// ---------------------------------------------------------------------------
// 这一层回答的是"这段时间各个动作分别往哪个方向走"，和另外两层不同：
//   首页 insight  —— 本周怎么样（固定 7 天，加权成一个分数）
//   评估页 findings —— 这一次训练怎么样
//   分析页 trend   —— 所选窗口内，每个动作的方向
// 所以它**不算分数**。再算一个分数就是首页的复读。
// ---------------------------------------------------------------------------

/**
 * 少于这么多次记录就不给趋势结论。
 *
 * 用两个点连一条线，那不是趋势，是画出来的结论。而且方向判定用的是
 * 前后半段均值，4 个点才保证每半段至少 2 个点。
 */
export const TREND_MIN_POINTS = 4

/**
 * 变化量达到**该动作目标的**这个比例，才算"有变化"。
 *
 * [待核定] 0.08 是拟的。
 *
 * 【为什么按目标的比例，而不是绝对度数】
 * 两种动作的尺度差一个量级：直腿抬高的目标只有 10°，屈膝滑动 90°。
 * 用一个绝对阈值（比如 5°）会两头都错 ——
 *   对直腿抬高，5° 是目标的 50%，小变化全被吞掉；
 *   对屈膝滑动，5° 只有目标的 5.6%，噪声被当成进步。
 *
 * 与 SINGLE_PROGRESS_THRESHOLD 同一个道理（那个用 MDC 卡在 12%），
 * 只是这里要判断的是"有没有动"，门槛比"算不算进步"低一档。
 */
export const TREND_MIN_RATIO = 0.08

/**
 * 绝对下限（度）。目标的 8% 在极小目标上会小到没有意义 ——
 * 直腿抬高目标的 8% 只有 0.8°，传感器噪声都比它大。
 */
export const TREND_MIN_ABS = 2

/**
 * 窗口短于这么多天时，提示"趋势参考价值有限"。
 *
 * 7 天最多 7 个数据点，前后半段各三四个，算出来的方向主要是噪声。
 * 不提示的话用户会拿三五天的数据当趋势。
 */
export const SHORT_WINDOW_DAYS = 14

/**
 * 窗口内温度越阈值的次数达到多少，报红灯而不是黄灯。
 *
 * 一次越阈值可能是热敷久了一点；反复越阈值说明做法有问题。
 */
export const TREND_TEMP_CRITICAL = 3

/**
 * 训练覆盖率低于多少算"练得太少"（实际训练天数 ÷ 从首次记录至今的天数）。
 *
 * [待核定] 0.4 是拟的。
 *
 * 分母刻意用**观察到的跨度**而不是窗口长度：一个三天前才开始训练、
 * 每天都练的患者，覆盖率是 100%，不该被说成"练得太少"。
 */
export const ADHERENCE_MIN_RATIO = 0.4
