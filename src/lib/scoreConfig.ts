// ============================================================================
// 评分参数
// ============================================================================
// 所有可调的数字集中在这里，算法实现里不再出现裸常数。
//
// 【为什么要单独一个文件】
// 这些值**理想情况下应该由懂康复的人核定**，而不是由写代码的人拍。
// 集中在一处，团队里康复方向的同学可以直接改这些数，不用去读算法实现。
//
// 每个参数都标了来源：
//   [待核定] —— 没有硬依据，按常见做法拟的，需要团队确认
//   [推导]   —— 由别处算出来的，改一处要改另一处
//
// 【答辩时的用法】
// 评委问"权重怎么定的"，翻这个文件：哪几个是文献/指南来的、
// 哪几个是待核定的，一目了然。比答"我们讨论定的"强。
// ============================================================================

// ---------------------------------------------------------------------------
// 时间窗口
// ---------------------------------------------------------------------------

/** 评分看的是最近多少天 */
export const WINDOW_DAYS = 7

/**
 * 基线：本周之前的那一段。
 *
 * 取 14 天而不是 7 天，是为了让"进步"有个稳定的参照 ——
 * 只取 7 天的话，上周恰好练得少就会让本周显得进步神速。
 */
export const BASELINE_DAYS = 14

/**
 * 认为基线够用的最少会话数。
 *
 * 少于这个数就不给进步度打分，取中性值 —— 用两三次记录算出来的
 * "进步 300%" 只会误导人。
 */
export const MIN_BASELINE_SESSIONS = 3

// ---------------------------------------------------------------------------
// 一、四项权重
// ---------------------------------------------------------------------------

/**
 * 四个分量的权重，和为 1。
 *
 * [待核定] 都是拟定的，**没有文献依据**。当前的取舍：
 *
 *   动作达标 0.40 —— 康复的核心是功能恢复，占最大头
 *   进步情况 0.30 —— 家属最关心"有没有变好"
 *   动作稳定 0.15 —— 重要但次要，且需要多次记录才看得出
 *   训练坚持 0.15 —— 依从性对结果影响很大，但它更像"前提条件"，
 *                    已经通过其它三项间接体现（不练就没有达标记录）
 *
 * ⚠️ 调整时注意：四项之和必须等于 1，否则总分不再落在 0~100。
 *    insight 的自检里有一条断言钉住这一点。
 */
export const WEIGHTS = {
  target: 0.4,
  progress: 0.3,
  stability: 0.15,
  adherence: 0.15,
} as const

// ---------------------------------------------------------------------------
// 二、进步情况
// ---------------------------------------------------------------------------

/**
 * 变化率达到这个幅度就算满分，负的这个幅度算零分，0 对应中间值。
 *
 * [待核定] ±20% 是拟的。选它的理由：康复有平台期，原地踏步不该被判成
 * 不及格；但 ±5% 又太容易触及，那样几乎人人满分，这一项就没有区分度了。
 *
 * 临床上更严谨的做法是用**最小可检测变化（MDC）**——同一患者重复测量时，
 * 小于 MDC 的变化无法与测量误差区分。膝关节活动度的 MDC 大约在 5°~10°，
 * 换算成相对值约 6%~11%，比 20% 小。**这一项值得让康复科重新定。**
 */
export const PROGRESS_FULL_SWING = 0.2

/** 进步度的中性值。0.5 = "持平"，既不加分也不扣分 */
export const PROGRESS_NEUTRAL = 0.5

// ---------------------------------------------------------------------------
// 三、动作稳定
// ---------------------------------------------------------------------------

/**
 * 变异系数（标准差 ÷ 均值）到多少算"完全不稳"。
 *
 * [待核定] 0.3 是拟的，没有依据。
 *
 * 用相对波动（CV）而不是绝对标准差：不同动作的完成度尺度不同，
 * 只有相对量才可比。
 */
export const STABILITY_CV_LIMIT = 0.3

/** 样本不足时的中性值。两次以下算不出波动 */
export const STABILITY_NEUTRAL = 0.5

/** 判断"稳定"用的分档，只影响文案措辞 */
export const STABILITY_GOOD_CV = 0.1
export const STABILITY_FAIR_CV = 0.2

// ---------------------------------------------------------------------------
// 四、训练坚持
// ---------------------------------------------------------------------------

/**
 * 康复方案建议的每周训练天数。
 *
 * [待核定] 按常见膝关节术后康复方案拟定的统一值。
 *
 * ⚠️ **真实产品里这一项必须按患者个体设定** —— 术后不同阶段的推荐频率
 *    差别很大（早期可能每天多次被动活动，后期可能隔天一次）。
 *    现在没有「患者-康复方案」这张表，只能先用统一值。
 *    要改成个性化的，需要给 profiles 或单独的方案表加一列。
 */
export const RECOMMENDED_DAYS_PER_WEEK = 5

// ---------------------------------------------------------------------------
// 五、安全下调
// ---------------------------------------------------------------------------

/**
 * 出现安全事件时对分数的下调系数。
 *
 * 【为什么是乘数而不是扣分项】
 * 安全事件的影响**不该是线性的** —— 它不能被"动作做得好"补回来。
 * 一次低温烫伤风险，不会因为患者本周动作达标率高就不算数。
 * 乘数天然表达这种"一票否决"，而加分制里它可以被别的项抵消掉。
 *
 * 【为什么按最严重的那一条算，不累加】
 * 3 次一般提醒并不等于比 1 次严重 3 倍。按最严重的算规则简单、
 * 家属也讲得清。次数会写在提示文案里，不藏。
 *
 * ⚠️ 实测过旧版的行为：有严重温度预警的一周仍然显示 85 分，
 *    只是把颜色变红了 —— 数字和颜色互相矛盾，而数字的说服力更强。
 *    这在医疗产品里是不能接受的。
 */
export const SAFETY_PENALTY = {
  /** 温度越过安全阈值、信号中断等 */
  critical: 0.6,
  /** 接近阈值、识别异常等 */
  warning: 0.85,
} as const

// ---------------------------------------------------------------------------
// 六、数据充分度
// ---------------------------------------------------------------------------

/**
 * 本周有多少次会话才算"数据充足"。
 *
 * [待核定] 5 次是拟的。
 *
 * 少于这个数时，分数会按比例向中性值收敛 —— 否则"本周只练了 1 次"
 * 也能算出一个看起来很确切的分数。实测过：1 次做满得 85 分、
 * 1 次不达标得 30 分，**1 个样本给出了 55 分的区分度**，这不合理。
 */
export const SUFFICIENT_SESSIONS = 5

/**
 * 数据不足时分数向这个值收敛。
 *
 * 【为什么是 65 而不是 60】
 * 60 正好压在"黄灯 / 红灯"的分界线上。收缩之后所有分数都会向中性值
 * 聚拢，落在分界线附近时，**颜色就由噪声决定了** —— 实测出现过
 * "1 次做满 61 分显示黄灯、1 次三成 56 分显示红灯"，5 分之差跨了一个
 * 颜色档，而两者的数据量同样不足，不该有这种区分。
 *
 * 取 65 落在中间档内部，避免这个问题。值本身表达的是"还看不出来"。
 */
export const NEUTRAL_SCORE = 65

// ---------------------------------------------------------------------------
// 七、分档
// ---------------------------------------------------------------------------

export type ScoreLevelKey =
  | 'excellent'
  | 'good'
  | 'fair'
  | 'watch'
  | 'alert'

export interface ScoreLevel {
  key: ScoreLevelKey
  /** 档位名。家属扫一眼就知道好坏 */
  label: string
  /** 一句话说明这个档位意味着什么 */
  detail: string
}

/**
 * 分档表。**从高到低**，第一个满足 `min` 的即命中。
 *
 * [待核定] 分界值是拟的。
 *
 * 分档的意义不只是分级，更是**解释**：一个"完美但处在平台期"的患者
 * 会拿到 85 分，单看数字家属会问"为什么不是 100"。配上
 * 「恢复良好 · 保持得很好」就不需要解释了。
 *
 * ⚠️ 分界值**必须与颜色分界对齐**（见 insight.ts 的 scoreBandFor：80 / 60）。
 *    两边漂了会出现"同一个标签配两种颜色" —— 实测踩过：51 分和 61 分
 *    都显示「需要关注」，一个红一个黄。
 *
 *    所以这里是 90 / 80 / 60 / 40：绿色档内分两级，中间档一级，
 *    红色档内分两级。三个颜色分界正好落在档位分界上。
 */
export const SCORE_LEVELS: (ScoreLevel & { min: number })[] = [
  { min: 90, key: 'excellent', label: '恢复优秀', detail: '与之前相比有明显进步' },
  { min: 80, key: 'good', label: '恢复良好', detail: '保持得很好，按当前方案继续' },
  { min: 60, key: 'fair', label: '稳步恢复', detail: '进展平稳，继续按方案训练' },
  { min: 40, key: 'watch', label: '需要关注', detail: '建议复查训练动作是否到位' },
  { min: 0, key: 'alert', label: '需要处理', detail: '建议联系康复治疗师' },
]


