// 二、进步情况
// ---------------------------------------------------------------------------

/**
 * 变化率达到这个幅度就算满分，负的这个幅度算零分，0 对应中间值。
 *
 * [待核定] ±20% 是拟的。选它的理由：康复有平台期，原地踏步不该被判成
 * 不及格；但 ±5% 又太容易触及，那样几乎人人满分，这一项就没有区分度了。
 *
 * 临床上更严谨的做法是用**最小可检测变化（MDC）**——同一患者重复测量时，
 * 小于 MDC 的变化无法与测量误差区分。膝关节活动度的 MDC 大约在 5°~10°，
 * 换算成相对值约 6%~11%，比 20% 小。**这一项值得让康复科重新定。**
 */
export const PROGRESS_FULL_SWING = 0.2

/** 进步度的中性值。0.5 = "持平"，既不加分也不扣分 */
export const PROGRESS_NEUTRAL = 0.5

// ---------------------------------------------------------------------------
// 三、动作稳定
// ---------------------------------------------------------------------------

/**
 * 变异系数（标准差 ÷ 均值）到多少算"完全不稳"。
 *
 * [待核定] 0.3 是拟的，没有依据。
 *
 * 用相对波动（CV）而不是绝对标准差：不同动作的完成度尺度不同，
 * 只有相对量才可比。
 */
export const STABILITY_CV_LIMIT = 0.3

/** 样本不足时的中性值。两次以下算不出波动 */
export const STABILITY_NEUTRAL = 0.5

/** 判断"稳定"用的分档，只影响文案措辞 */
export const STABILITY_GOOD_CV = 0.1
export const STABILITY_FAIR_CV = 0.2

/**
 * 稳定项低到这个分，才值得在建议里提"把动作放慢"。
 *
 * [推导] 由 STABILITY_FAIR_CV 反推，**不要单独调这个数** ——
 * 它必须与文案的门槛一致。文案在 cv ≥ STABILITY_FAIR_CV 时才说
 * "忽大忽小"，建议就该在同一处才出手，否则会出现
 * "上面写着总体可控、下面让人放慢动作"这种自相矛盾。
 *
 * 【为什么稳定项需要单独的门槛】
 * 四个分量的"正常水平"不同：训练坚持要么够要么不够、动作达标通常
 * 接近满分，而稳定天然带波动。拿它们的绝对值比大小挑最弱项，
 * 低分永远出在稳定项上 —— 实测就是这么错的。
 */
export const STABILITY_CONCERN_SCORE = 1 - STABILITY_FAIR_CV / STABILITY_CV_LIMIT

