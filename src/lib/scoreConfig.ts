// ---------------------------------------------------------------------------
// 五、安全下调
// ---------------------------------------------------------------------------

/**
 * 出现安全事件时对分数的下调系数。
 *
 * 【为什么是乘数而不是扣分项】
 * 安全事件的影响**不该是线性的** —— 它不能被"动作做得好"补回来。
 * 一次低温烫伤风险，不会因为患者本周动作达标率高就不算数。
 * 乘数天然表达这种"一票否决"，而加分制里它可以被别的项抵消掉。
 *
 * 【为什么按最严重的那一条算，不累加】
 * 3 次一般提醒并不等于比 1 次严重 3 倍。按最严重的算规则简单、
 * 家属也讲得清。次数会写在提示文案里，不藏。
 *
 * [待核定] 这两个数**没有依据**，是拟的。2026-09-22 从 0.6 / 0.85 调成
 *    现在的 0.80 / 0.92。调小的理由：
 *
 *      ① 原先 40% 太重。一周练满、动作全达标、进步明显（原始分 100），
 *         一次严重事件直接掉到 60 分 —— 等于把一周的努力抹平。
 *      ② 乘数是按比例扣，**对本来就没做好的周惩罚更重**：
 *         65 分的一周 ×0.6 = 39。做得差的人被罚两次，不合理。
 *
 *    康复科若认为"安全事件必须更重"，调回去也行 —— 但先看下面这段。
 *
 * ⚠️ **乘数保证不了"评分颜色与风险颜色一致"，不要写那样的断言。**
 *
 *    它按比例扣，所以原始分越高、扣完剩得越多：100 分的周 ×0.80 还剩
 *    80 分，而「有严重事件就报红」的 bandFor 会给出红 —— 两者必然打架。
 *    （原先的 0.60 也不行：100 × 0.60 正好等于 60，压在下边界上。）
 *
 *    这两个本来就不是一回事 —— 见 insight.ts 里 Insight.band 的注释：
 *    分数说的是"恢复得怎么样"，风险说的是"有没有危险"。界面上数字用
 *    scoreBand 上色、风险由各张卡片自己的 band 表达，分开是对的。
 *
 *    历史上有一条 `scoreBand === band` 的断言就是错的。它一直绿，只是
 *    因为喂进去的数据（原始分 85）碰巧绕开了边界，不是因为它成立。
 *
 * ⚠️ 另一条不能动的：有严重温度预警的一周**仍然显示 85 分**、只是把颜色
 *    变红 —— 这个旧行为是促成扣分机制的原因（数字和颜色互相矛盾，
 *    而数字的说服力更强）。别因为系数调小了就把扣分整个拿掉。
 */
export const SAFETY_PENALTY = {
  /** 温度越过安全阈值、信号中断等 */
  critical: 0.8,
  /** 接近阈值、识别异常等 */
  warning: 0.92,
} as const

