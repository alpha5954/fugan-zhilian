// ============================================================================
// 功能权限：「AI 深度分析」是可选项
// ============================================================================
// 产品定位是**基础评估免费、AI 综合解读是高级功能**：
//
//   规则结论（免费，始终显示）  ← 可逐条核对，答辩时能展开讲依据
//          │
//          └─► AI 深度分析（可选）  ← 在规则结论之上做综合解读，
//                                    有自己的外壳和来源标签，不与之混排
//
// 所以 AI 这条路从一开始就要有闸门 —— 但**现在不做计费**。
// 需要一个付费后端（DB 加 plan 列、支付流程、服务端校验）才能真的收钱，
// 那套东西现在不存在。这里只留**接缝**，让将来翻转不是重写。
//
// ============================================================================
// ⚠️ 客户端这个闸门只是体验，不是权限
// ============================================================================
// 线上是静态站点，任何打开页面的人都能拿到一个匿名会话（访客模式），
// 然后**直接调那个 Edge Function**，绕开整个界面。所以：
//
//   客户端这道闸门 → 决定「按钮点不点得动、要不要显示升级引导」
//   服务端那道闸门 → 决定「这次调用花不花得出去钱」   ← 真正拦得住的是它
//
// 服务端那道在 supabase/functions/ai-analysis/index.ts 的 isEntitled() 里，
// 现在直接 return true，注释写着它将来必须变成什么。
//
// 两边的开关**必须一起翻**。只翻客户端 = 界面看起来收费了，钱照花。
// ============================================================================

/**
 * 用户档位。
 *
 * `free`  —— 现在所有人都是这个（还没有计费）
 * `plus`  —— 将来订阅了 AI 分析的账号
 */
export type AiPlan = 'free' | 'plus'

/**
 * ★ 上线开关。
 *
 * `false` —— AI 分析对所有人开放（当前状态：答辩要能演示）
 * `true`  —— 只有 `plus` 能用，界面上显示升级引导
 *
 * 翻转这个常量的同时，必须把 Edge Function 里的同名开关也翻掉，
 * 并把 `isEntitled()` 换成真的查询。见本文件头部那段。
 */
export const AI_REQUIRES_PLAN = false

export interface AiAccess {
  /** 能不能用 */
  allowed: boolean
  /** 不能用时给界面的一句中文说明。能用时为 null */
  reason: string | null
}

/**
 * 判断当前用户能不能用 AI 分析。
 *
 * 刻意做成纯函数（收 plan，不自己去读 store）：这样 `scripts/check-ai.ts`
 * 能把三种组合都钉住，不必起一个浏览器。
 */
export function aiAccess(plan: AiPlan = 'free'): AiAccess {
  if (!AI_REQUIRES_PLAN) return { allowed: true, reason: null }
  if (plan === 'plus') return { allowed: true, reason: null }

  return {
    allowed: false,
    reason: 'AI 深度分析是高级功能。基础评估结论不受影响，始终免费可用。',
  }
}
