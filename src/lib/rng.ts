// ============================================================================
// 可复现的随机源
// ============================================================================
//
// 【为什么不用 Math.random】
// 演示数据每次刷新页面都会变。用户看到的后果很具体：**同一个演示页面，
// 刷新一次分数从 81 变成 77**。排练时记住的是 81，台上变成 77 —— 对一个
// 要拿去比赛的演示来说，这是不可控。
//
// 换成带种子的伪随机之后，同样的种子永远给出同一组数据。
//
// 【为什么把随机源做成参数，而不是全局替换】
// 实时监测页**应该**每次都不一样 —— 那是"正在发生的信号"，
// 每次都相同反而不真实。
//
// 所以随机源是**逐个传进去的**：
//   * 演示数据 → 固定种子，可复现
//   * 实时监测 → Math.random，每次都不同
// 同一个模拟器代码，两种用法。
// ============================================================================

/** 返回 [0, 1) 的随机数。签名与 Math.random 一致，可直接互换 */
export type Rng = () => number

/**
 * mulberry32 —— 一个 32 位状态的伪随机数发生器。
 *
 * 选它的理由：实现只有几行、无依赖、分布质量对演示数据足够、
 * 而且**状态只有一个整数**（容易做固定种子）。
 * 不是密码学安全的，这里也不需要。
 */
export function makeRng(seed: number): Rng {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/**
 * 演示数据的固定种子。
 *
 * 改这个数会得到**另一组同样合理、但不同**的演示数据。
 * 想让演示换个"病人"，改这里即可 —— 但改完要重新看一眼分数是否仍然
 * 落在合理的档位里（比如别调出一个 38 分）。
 */
export const DEMO_SEED = 20260922
