// ============================================================================
// 读取设计令牌的运行时值
// ============================================================================
// ECharts 把图画在 canvas 上，**不会解析 CSS 自定义属性** —— 传
// 'var(--brand-700)' 进去，得到的是一片透明或黑色，而不是那个颜色。
//
// 所以图表必须拿到字面色值。但直接在 TS 里抄一份十六进制值，就等于把
// 品牌色存在两个地方，改一处忘另一处迟早出错 —— 这正是这次重构要消除的
// 那类问题。
//
// 折中：运行时从 CSS 变量读出来，并缓存。单一数据源仍然是 tokens.css。
// ============================================================================

const cache = new Map<string, string>()

/**
 * 取某个设计令牌的当前值。
 *
 * 带缓存 —— 实时监测页每秒要重建 4 张图的配置，每次都调
 * getComputedStyle 会明显掉帧。
 *
 * ⚠️ 缓存意味着**运行期改主题不会生效**。本项目的主题是静态的，
 *    没有切换需求；若将来要做深色模式，需要在这里加一个失效机制。
 *
 * ⚠️ 不要在模块顶层调用。按需引入的 CSS 是在模块求值之后才注入的，
 *    顶层调用可能读到空值。要在函数内部、渲染时再取。
 */
export function token(name: `--${string}`): string {
  let value = cache.get(name)
  if (value === undefined) {
    value = getComputedStyle(document.documentElement)
      .getPropertyValue(name)
      .trim()
    cache.set(name, value)
  }
  return value
}
